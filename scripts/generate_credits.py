"""Generate local About data from the licensing record. No network requests."""
import json
import re
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate():
    text = (ROOT / "CREDITS.md").read_text(encoding="utf-8")
    rows = []
    seen = set()
    for line in text.splitlines():
        if line.startswith("| ") and not line.startswith("| Component |"):
            cells = [c.strip() for c in line.strip("|").split("|")]
            if len(cells) == 7 and cells[6] not in ("", "-"):
                links = re.findall(r"\[([^\]]+)\]\((https?://[^\s)]+)\)", cells[6])
                if not links:
                    raise ValueError("About credits need a project name and URL")
                for name, url in links:
                    if (name, url) not in seen:
                        rows.append(f"{name}: {url}")
                        seen.add((name, url))
        elif line.startswith("- ["):
            for name, url in re.findall(r"\[([^\]]+)\]\((https?://[^\s)]+)\)", line):
                if (name, url) not in seen:
                    rows.append(f"{name}: {url}")
                    seen.add((name, url))
    header = "// Generated by scripts/generate_credits.py from CREDITS.md.\n#pragma once\n// clang-format off\n"
    header += 'namespace config {\nconstexpr const char *kProjectUrl = "https://github.com/jedney/esp32-usr-modem";\nconstexpr const char *kCredits[] = {\n'
    rows = [unicodedata.normalize("NFKD", row).encode("ascii", "replace").decode() for row in rows]
    header += "".join("    " + json.dumps(row, ensure_ascii=True) + ",\n" for row in rows)
    header += "};\n}  // namespace config\n// clang-format on\n"
    output = ROOT / "lib/config/src/credits_generated.h"
    if not output.exists() or output.read_text(encoding="utf-8") != header:
        output.write_text(header, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    generate()
